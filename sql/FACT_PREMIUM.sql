CREATE OR REPLACE TABLE GOLD.FACT_PREMIUM (
    TRANSACTION_ID VARCHAR,
    CUSTOMER_KEY NUMBER,
    POLICY_KEY NUMBER,
    TRANSACTION_DATE DATE,
    PREMIUM_AMOUNT NUMBER(18,2),
    PAID_AMOUNT NUMBER(18,2),
    OUTSTANDING_AMOUNT NUMBER(18,2),
    PAYMENT_STATUS VARCHAR,
    PAYMENT_MODE VARCHAR
);

INSERT INTO GOLD.FACT_PREMIUM (
    TRANSACTION_ID,
    CUSTOMER_KEY,
    POLICY_KEY,
    TRANSACTION_DATE,
    PREMIUM_AMOUNT,
    PAID_AMOUNT,
    OUTSTANDING_AMOUNT,
    PAYMENT_STATUS,
    PAYMENT_MODE
)
SELECT
    P.TRANSACTION_ID,
    C.CUSTOMER_KEY,
    D.POLICY_KEY,
    P.TRANSACTION_DATE,
    P.PREMIUM_AMOUNT,
    P.PAID_AMOUNT,
    GREATEST(P.PREMIUM_AMOUNT - P.PAID_AMOUNT, 0),
    P.PAYMENT_STATUS,
    P.PAYMENT_MODE
FROM SILVER.SLV_PREMIUMS P
INNER JOIN GOLD.DIM_CUSTOMER C
    ON P.CUSTOMER_ID = C.CUSTOMER_ID
INNER JOIN GOLD.DIM_POLICY D
    ON P.POLICY_ID = D.POLICY_ID;
