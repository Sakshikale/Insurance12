CREATE OR REPLACE TABLE SILVER.SLV_PREMIUMS AS
SELECT DISTINCT
    TRIM(TRANSACTION_ID) AS TRANSACTION_ID,
    TRIM(POLICY_ID) AS POLICY_ID,
    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
    TRY_TO_DATE(TRANSACTION_DATE) AS TRANSACTION_DATE,
    TRY_TO_NUMBER(PREMIUM_AMOUNT, 18, 2) AS PREMIUM_AMOUNT,
    TRY_TO_NUMBER(PAID_AMOUNT, 18, 2) AS PAID_AMOUNT,
    INITCAP(TRIM(PAYMENT_STATUS)) AS PAYMENT_STATUS,
    INITCAP(TRIM(PAYMENT_MODE)) AS PAYMENT_MODE
FROM BRONZE.BR_PREMIUMS
WHERE TRANSACTION_ID IS NOT NULL;
