CREATE OR REPLACE TABLE SILVER.SLV_POLICIES AS
SELECT DISTINCT
    TRIM(POLICY_ID) AS POLICY_ID,
    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
    INITCAP(TRIM(POLICY_TYPE)) AS POLICY_TYPE,
    INITCAP(TRIM(POLICY_STATUS)) AS POLICY_STATUS,
    TRY_TO_NUMBER(COVERAGE_AMOUNT, 18, 2) AS COVERAGE_AMOUNT,
    TRY_TO_NUMBER(ANNUAL_PREMIUM, 18, 2) AS ANNUAL_PREMIUM,
    TRY_TO_DATE(START_DATE) AS START_DATE,
    TRY_TO_DATE(END_DATE) AS END_DATE
FROM BRONZE.BR_POLICIES
WHERE POLICY_ID IS NOT NULL;
