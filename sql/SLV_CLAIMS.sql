CREATE OR REPLACE TABLE SILVER.SLV_CLAIMS AS
SELECT DISTINCT
    TRIM(CLAIM_ID) AS CLAIM_ID,
    TRIM(POLICY_ID) AS POLICY_ID,
    TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
    TRY_TO_DATE(CLAIM_DATE) AS CLAIM_DATE,
    INITCAP(TRIM(CLAIM_TYPE)) AS CLAIM_TYPE,
    TRY_TO_NUMBER(CLAIM_AMOUNT, 18, 2) AS CLAIM_AMOUNT,
    TRY_TO_NUMBER(APPROVED_AMOUNT, 18, 2) AS APPROVED_AMOUNT,
    INITCAP(TRIM(CLAIM_STATUS)) AS CLAIM_STATUS
FROM BRONZE.BR_CLAIMS
WHERE CLAIM_ID IS NOT NULL;
